// Run against a built and served site; see README.md in this directory.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");
const { default: AxeBuilder } = require("@axe-core/playwright");

const siteDirectory = path.resolve(process.argv[2] || "_site");
const baseURL = process.argv[3] || "http://127.0.0.1:4000";
const reportPath = process.env.A11Y_REPORT || "/tmp/trela-accessibility.json";

function pagesIn(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) return pagesIn(filename);
    // Redirect stubs are generated by jekyll-redirect-from, outside our layout.
    if (!filename.endsWith(".html") || !fs.readFileSync(filename, "utf8").includes("<main")) return [];
    return ["/" + path.relative(siteDirectory, filename).split(path.sep).join("/")];
  });
}

async function visit(page, route) {
  await page.goto(baseURL + route);
  await page.evaluate(() => document.fonts.ready);
}

async function keyboardChecks(browser) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  await visit(page, "/news/");
  await page.keyboard.press("Tab");
  assert.equal(await page.locator(".skip-link").evaluate((el) => el === document.activeElement), true);
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => document.activeElement.id === "main-content");
  await page.keyboard.press("Tab");
  assert.equal(await page.evaluate(() => document.querySelector("main").contains(document.activeElement)), true);

  const toggle = page.getByRole("checkbox", { name: "Show navigation" });
  const navigation = page.getByRole("navigation", { name: "Primary" });
  assert.equal(await navigation.isVisible(), false);
  await toggle.focus();
  await page.keyboard.press("Space");
  assert.equal(await toggle.isChecked(), true);
  assert.equal(await navigation.isVisible(), true);
  assert.equal(await toggle.getAttribute("aria-controls"), await navigation.getAttribute("id"));
  await page.keyboard.press("Tab");
  const firstLink = navigation.locator("a").first();
  assert.equal(await firstLink.evaluate((el) => el === document.activeElement), true);
  await page.waitForFunction(() => document.activeElement._tippy?.state.isVisible);
  await page.keyboard.press("Escape");
  assert.equal(await toggle.isChecked(), false);
  assert.equal(await toggle.evaluate((el) => el === document.activeElement), true);
  assert.equal(await page.evaluate(() => [...document.querySelectorAll("[data-tooltip]")].some((el) => el._tippy?.state.isVisible)), false);

  const search = page.getByRole("textbox", { name: "Search items on this page" });
  const status = page.getByRole("status");
  await search.fill("no-results-accessibility-check");
  await page.waitForFunction(() => document.querySelector(".search-status").textContent.startsWith("Showing 0 of"));
  assert.equal(await page.locator(".post-excerpt:visible").count(), 0);
  const clear = page.getByRole("button", { name: "clear search", exact: true });
  await clear.focus();
  await page.keyboard.press("Enter");
  assert.equal(await search.inputValue(), "");
  assert.equal(await search.evaluate((el) => el === document.activeElement), true);
  assert.match(await status.textContent(), /^Showing all \d+ results$/);
  assert.ok(await page.locator(".post-excerpt:visible").count() > 0);
  // Clearing while a delayed search is pending must not reapply the old query.
  await search.fill("stale-query");
  await clear.focus();
  await page.keyboard.press("Enter");
  await page.waitForTimeout(1200);
  assert.equal(await search.inputValue(), "");
  assert.match(await status.textContent(), /^Showing all \d+ results$/);

  const dark = page.getByRole("switch", { name: "Dark mode", exact: true });
  await dark.focus();
  await page.keyboard.press("Space");
  assert.equal(await dark.isChecked(), true);
  assert.equal(await page.locator("html").getAttribute("data-dark"), "true");
  await page.reload();
  assert.equal(await dark.isChecked(), true);
  await visit(page, "/404.html");
  assert.equal(await page.getByRole("textbox", { name: "Search site with Google" }).count(), 1);
  await context.close();
}

(async () => {
  const browser = await chromium.launch();
  const report = { pages: [], keyboardChecks: "not run" };
  try {
    const routes = pagesIn(siteDirectory).sort();
    assert.ok(routes.length > 0, "No rendered pages found");
    for (const dark of ["false", "true"]) {
      const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
      await context.addInitScript((value) => localStorage.setItem("dark-mode", value), dark);
      const page = await context.newPage();
      for (const route of routes) {
        await visit(page, route);
        const results = await new AxeBuilder({ page })
          .withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"])
          .analyze();
        const summarize = (rules) => rules.map(({ id, impact, nodes }) => ({
          id, impact, nodes: nodes.map(({ target, html, failureSummary, any }) => ({ target, html, failureSummary, checks: any })),
        }));
        report.pages.push({ route, dark, violations: summarize(results.violations), incomplete: summarize(results.incomplete) });
        console.log(`${dark === "true" ? "dark" : "light"} ${route}: ${results.violations.map((v) => `${v.id} (${v.nodes.length})`).join(", ") || "no automated violations"}`);
      }
      await context.close();
    }
    await keyboardChecks(browser);
    report.keyboardChecks = "passed";
    const nonContrast = report.pages.flatMap((page) => page.violations.filter((v) => v.id !== "color-contrast"));
    assert.equal(nonContrast.length, 0, "Non-contrast violations remain; inspect the JSON report");
    console.log(`Keyboard checks passed. ${routes.length} pages checked in both modes. Report: ${reportPath}`);
  } finally {
    fs.writeFileSync(reportPath, JSON.stringify(report, null, 2));
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
